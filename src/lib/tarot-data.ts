function mk(
  suit: Suit,
  arcana: Arcana,
  number: number,
  data: [string, string[], string[], string, string]
): TarotCard {
  const suitNames: Record<string, string> = {
    wands: "权杖",
    cups: "圣杯",
    swords: "宝剑",
    pentacles: "钱币",
  };
  return {
    id: `${suit}-${arcana === "court" && number >= 11 ? `court-${number}` : number}`,
    name: data[0],
    en:
      arcana === "court"
        ? `${suitNames[suit!]} ${data[0].slice(2)}`
        : `${suitNames[suit!]} ${number}`,
    suit,
    arcana,
    number,
    element: suit === "wands" ? "火" : suit === "cups" ? "水" : suit === "swords" ? "风" : suit === "pentacles" ? "土" : "—",
    upright: data[1],
    reversed: data[2],
    meaning: data[3],
    reversedMeaning: data[4],
  };
}

function wandsDeck() {
  return wands(1);
}

